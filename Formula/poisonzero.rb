  desc "Protects AI agent memory files from poisoning (fail-closed, AI-scored)"
  homepage "https://poisonzero.com"
  version "1.16.0"
  license :cannot_represent

  on_macos do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-arm64"
      sha256 "8db952131bc5d8b21106f1bceb79e8a63af3cf84fb8d44f47178ad9c139da9b5"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-amd64"
      sha256 "18e71523bea5711a9898706eba8d41bc734f79336d35a5621f48f785da8ae6a4"
    end
  end

  on_linux do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-arm64"
      sha256 "8fdef60025206931a2306068a4ed0badf3bf9b694f8e99bd3536012cdbacb4d2"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-amd64"
      sha256 "c34949c625cc8ee8b476a2e6349c37b429ff1d601bfccc8b6fc5296a18c799cc"
    end
