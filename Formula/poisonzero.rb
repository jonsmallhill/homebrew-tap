  desc "Protects AI agent memory files from poisoning (fail-closed, AI-scored)"
  homepage "https://poisonzero.com"
  version "1.16.22"
  license :cannot_represent

  on_macos do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-arm64"
      sha256 "72b0a628b0b108857824ecfe9d865e4cbfc0f93621ae4e480e21b3f72ec1680a"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-amd64"
      sha256 "08dc6f7f65727e52858a7913cd5857de22a98943a9f35b7e16c88cca11d83b4a"
    end
  end

  on_linux do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-arm64"
      sha256 "7267ad4d667d361882e7caa346ad62dc7cf9058650726c5ac35c3d3143a0f432"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-amd64"
      sha256 "83bfbee2fe56c85c01fe324cf1a3f0242b3aea4d7cebf2ae310de0c49e043fb4"
    end
