  homepage "https://poisonzero.com"
  version "1.16.1"
  license :cannot_represent

  on_macos do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-arm64"
      sha256 "d8d6aea7438731f6551f8a793d7bc89bfe46a530ea5ccedc3ab591f9e1ab8c41"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-amd64"
      sha256 "7ce9fb23a76221da00d936c71002529f736910b0e288080183afea5e28db1836"
    end
  end

  on_linux do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-arm64"
      sha256 "6f8a4e1c7495d23231211aefc59ac342a62c8c3dc598c01bc000a15cd2fc83cc"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-amd64"
      sha256 "b6769fa7a96793fa8b746716f4f8478b28d745397e2847d79a9e7590bee734a8"
    end
