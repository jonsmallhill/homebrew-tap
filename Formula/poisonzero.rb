  desc "Protects AI agent memory files from poisoning (fail-closed, AI-scored)"
  homepage "https://poisonzero.com"
  version "1.16.44"
  license :cannot_represent

  on_macos do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-arm64"
      sha256 "a7a9b1573b75968b5a36e13d614f046d67925d374febec99c9f557008cc35a9c"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-darwin-amd64"
      sha256 "c0927718f69f2fab4a6d2a74c28da05c98856ffc83a13890b04ad1e94fdbf9c9"
    end
  end

  on_linux do
    on_arm do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-arm64"
      sha256 "b466e5bb9acda5e49479e605cd66e17b2c79574b64431b5c49bace1798652fe9"
    end
    on_intel do
      url "https://poisonzero.com/dl/v#{version}/poisonzero-linux-amd64"
      sha256 "4ef8dd36c2060e3a4b656fd0829938410f4718646ae843a99d1fcf1747760dc2"
    end
